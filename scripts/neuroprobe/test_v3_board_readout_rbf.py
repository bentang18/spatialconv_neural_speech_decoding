def test_trace_invariant_holds_so_lambda_means_the_same_thing_at_every_gamma():
    """diag(K)==1 ⇒ trace(K)/n==1. Asserted inside the fit; this pins that the assert is reachable
    and true on real inputs, so the γ and λ axes stay separable."""
    z, _y, ev = _split()
    g, _k = _linear_grams(z, ev)
    sq = np.diag(g).copy()
    d2 = np.maximum(sq[:, None] + sq[None, :] - 2.0 * g, 0.0)
    med = float(np.median(d2[np.triu_indices(len(sq), k=1)]))
    for gm in GAMMA_MULTS:
        k = np.exp(-(gm / med) * d2)
        assert np.allclose(np.diag(k), 1.0)
        assert abs(float(np.trace(k)) / len(sq) - 1.0) < 1e-9


def test_returned_grid_has_the_SAME_SHAPE_as_the_linear_one():
    """_select_lam, the tie census and the lam_pin diagnostics are shared code. If the RBF fit
    returned a differently-keyed grid they would silently read the wrong thing."""
    z, y, ev = _split()
    lin, rbf = _lam_grid(z, y, ev), _lam_grid_rbf(z, y, ev)
    assert set(rbf) == set(lin)
    for name in ("val", "test"):
        assert sorted(rbf[name]) == sorted(lin[name]) == sorted(LAM_MULTS)


def test_gamma_selection_is_recorded_for_the_end_of_grid_census():
    before = R._RBF_STATS["fits"]
    z, y, ev = _split()
    _lam_grid_rbf(z, y, ev)
    assert R._RBF_STATS["fits"] == before + 1
    assert sum(R._RBF_STATS["picked"].values()) == R._RBF_STATS["fits"]
    assert set(R._RBF_STATS["picked"]) <= set(GAMMA_MULTS)


def test_gamma_is_selected_on_VAL_never_on_TEST():
    """The one way this harness could cheat. Corrupting the test half must not change which γ wins,
    and therefore must not change the val curve that selection reads."""
    z, y, ev = _split(seed=11)
    clean = _lam_grid_rbf(z, y, ev)
    zt, yt = ev["test"]
    poisoned = dict(ev, test=(zt, 1.0 - yt))       # flip every test label
    dirty = _lam_grid_rbf(z, y, poisoned)
    for m in LAM_MULTS:
        assert clean["val"][m] == dirty["val"][m], "test labels leaked into the val curve"


def test_degenerate_train_half_returns_nan_not_a_crash_or_a_number():
    """All rows identical ⇒ no length scale exists. Inventing one would print a scored cell for a
    fit that never happened."""
    z, y, ev = _split(kind="constant")
    out = _lam_grid_rbf(z, y, ev)
    assert all(np.isnan(out["test"][m]) for m in LAM_MULTS)


def test_single_row_train_half_is_nan():
    z, y, ev = _split()
    out = _lam_grid_rbf(z[:1], y[:1], ev)
    assert all(np.isnan(out["test"][m]) for m in LAM_MULTS)


@pytest.mark.parametrize("kind", ["linear", "xor"])
def test_no_nan_leaks_into_a_healthy_fit(kind):
    z, y, ev = _split(kind=kind, seed=7)
    out = _lam_grid_rbf(z, y, ev)
    assert all(np.isfinite(out["test"][m]) for m in LAM_MULTS)
